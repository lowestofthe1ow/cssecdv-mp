    public void init(Main controller){
        this.setDefaultCloseOperation(WindowConstants.EXIT_ON_CLOSE);
        this.setTitle("CSSECDV - SECURITY Svcs");
        this.setLocationRelativeTo(null);
        
        ErrorHandler.setFailsafe(this::logout);
        this.main = controller;
        this.auth = new AuthService(main.sqlite);
        idleTimer = new javax.swing.Timer(IDLE_TIMEOUT_MS, new java.awt.event.ActionListener() {
            public void actionPerformed(java.awt.event.ActionEvent evt) {
                idleLogout();
            }
        });
        idleTimer.setRepeats(false);
        java.awt.Toolkit.getDefaultToolkit().addAWTEventListener(new java.awt.event.AWTEventListener() {
            public void eventDispatched(java.awt.AWTEvent evt) {
                if (currentUser != null) {
                    idleTimer.restart();
                }
            }
        }, java.awt.AWTEvent.MOUSE_EVENT_MASK | java.awt.AWTEvent.MOUSE_MOTION_EVENT_MASK | java.awt.AWTEvent.KEY_EVENT_MASK);
        loginPnl.frame = this;
        registerPnl.frame = this;
        
        adminHomePnl.init(main.sqlite);
        clientHomePnl.init(main.sqlite);
        managerHomePnl.init(main.sqlite);
        staffHomePnl.init(main.sqlite);
        
        Container.setLayout(frameView);
        Container.add(loginPnl, "loginPnl");
        Container.add(registerPnl, "registerPnl");
        Container.add(HomePnl, "homePnl");
        frameView.show(Container, "loginPnl");
        
        Content.setLayout(contentView);
        Content.add(adminHomePnl, "adminHomePnl");
        Content.add(managerHomePnl, "managerHomePnl");
        Content.add(staffHomePnl, "staffHomePnl");
        Content.add(clientHomePnl, "clientHomePnl");
        
        this.setVisible(true);
    }
    
    public void mainNav(){
        if (currentUser == null) {
            loginNav();
            return;
        }
        String home = AccessControl.homePanelFor(currentUser);
        if (home == null) {
            logout();
            return;
        }
        idleTimer.restart();
        if (AccessControl.PANEL_ADMIN.equals(home)) {
            adminHomePnl.showPnl("home");
        } else if (AccessControl.PANEL_MANAGER.equals(home)) {
            managerHomePnl.showPnl("home");
        } else if (AccessControl.PANEL_STAFF.equals(home)) {
            staffHomePnl.showPnl("home");
        } else {
            clientHomePnl.showPnl("home");
        }
        contentView.show(Content, home);
        frameView.show(Container, "homePnl");
    }
    
    public boolean authorize(String resource){
        if (currentUser == null) {
            loginNav();
            return false;
        }
        if (AccessControl.check(currentUser, resource)) {
            return true;
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Access denied.",
                "Access Denied", javax.swing.JOptionPane.ERROR_MESSAGE);
        if (!AccessControl.isActive(currentUser)) {
            logout();
        }
        return false;
    }
    
    public static Frame of(java.awt.Component component){
        java.awt.Window w = javax.swing.SwingUtilities.getWindowAncestor(component);
        return (w instanceof Frame) ? (Frame) w : null;
    }
    
    public static boolean guard(java.awt.Component component, String resource){
        Frame f = of(component);
        return f != null && f.authorize(resource);
    }
    
    public void loginNav(){
        if (idleTimer != null) {
            idleTimer.stop();
        }
        loginPnl.clearFields();
        frameView.show(Container, "loginPnl");
    }
    
    public void registerNav(){
        frameView.show(Container, "registerPnl");
    }
    
    public void logout(){
        endSession("LOGOUT", "User logged out");
    }
    
    private void endSession(String event, String desc){
        if (currentUser != null) {
            SecurityLogger.log(event, currentUser.getUsername(), desc);
        }
        currentUser = null;
        loginNav();
    }
    
    private void idleLogout(){
        if (currentUser == null) {
            return;
        }
        endSession("SESSION_TIMEOUT", "Session ended after inactivity");
        javax.swing.JOptionPane.showMessageDialog(this, "You were logged out due to inactivity.",
                "Session Expired", javax.swing.JOptionPane.INFORMATION_MESSAGE);
    }
    
    public boolean loginAction(String username, char[] password){
        AuthService.LoginResult r = auth.login(username, password);
        if (!r.success) {
            javax.swing.JOptionPane.showMessageDialog(this, AuthService.GENERIC_LOGIN_ERROR,
                    "Login Failed", javax.swing.JOptionPane.ERROR_MESSAGE);
            return false;
        }
        currentUser = r.user;
        mainNav();
        String info = (r.lastAttempt == null)
                ? "This is your first login."
                : "Last login attempt: " + r.lastAttempt + "\nStatus: " + r.lastStatus;
        javax.swing.JOptionPane.showMessageDialog(this, info,
                "Welcome, " + r.user.getUsername(), javax.swing.JOptionPane.INFORMATION_MESSAGE);
        return true;
    }
    
    public boolean registerAction(String username, char[] password, char[] confpass){
        String error = auth.register(username, password, confpass);
        if (error != null) {
            javax.swing.JOptionPane.showMessageDialog(this, error,
                    "Registration", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }
        javax.swing.JOptionPane.showMessageDialog(this, "Account created. You can now log in.",
                "Registration", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        return true;
    }
    
    public String changeUserPassword(String targetUsername, char[] currentPw, char[] newPw, char[] confirm){
        if (currentUser == null) {
            loginNav();
            return AuthService.GENERIC_ERROR;
        }
        String error = auth.changePasswordFor(currentUser, targetUsername, currentPw, newPw, confirm);
        if (error != null && auth.isAccountDisabled(currentUser.getUsername())) {
            logout();
        }
        return error;
    }

